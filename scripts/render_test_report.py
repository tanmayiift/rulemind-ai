#!/usr/bin/env python3
"""Render TEST_RESULTS.md from a run of scripts/run_all_tests.sh.

Every number here is read from a runner's own output. That is the point: README.md and CLAUDE.md
both carried hardcoded test counts that drifted ~25% below reality (1369 claimed against 1892
actual), because a human typed them once and nothing ever checked them again. A generated file
cannot drift without someone noticing the diff.

It also writes a GitHub Actions job summary when $GITHUB_STEP_SUMMARY is set, so the same numbers
appear on the run page. Before this there were ZERO occurrences of GITHUB_STEP_SUMMARY in the
repo -- a green CI run published nothing at all, and every test artifact was `if: failure()`.
"""
from __future__ import annotations

import argparse
import os
import subprocess
from datetime import datetime, timezone
from pathlib import Path

BADGE = {"pass": "✅", "FAIL": "❌", "skipped": "⬜"}


def git(*args: str) -> str:
    try:
        return subprocess.run(["git", *args], capture_output=True, text=True,
                              timeout=10).stdout.strip()
    except Exception:  # noqa: BLE001 - a report must render outside a git checkout too
        return ""


def read_summary(path: Path):
    rows = []
    if not path.exists():
        return rows
    for line in path.read_text().splitlines():
        parts = line.split("\t")
        if len(parts) == 5:
            rows.append(dict(zip(("name", "label", "status", "count", "duration"), parts)))
    return rows


def render(rows) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    sha, branch = git("rev-parse", "--short", "HEAD"), git("rev-parse", "--abbrev-ref", "HEAD")
    failed = [r for r in rows if r["status"] == "FAIL"]
    skipped = [r for r in rows if r["status"] == "skipped"]
    passed = [r for r in rows if r["status"] == "pass"]

    total = 0
    for r in rows:
        if r["count"].isdigit():
            total += int(r["count"])

    verdict = ("**All lanes green.**" if not failed
               else "**{0} lane(s) FAILED.**".format(len(failed)))

    out = ["# Test results", "",
           "Generated by `scripts/run_all_tests.sh` — every number below is read from the "
           "runner's own output, never typed. Re-run that script to refresh this file.", "",
           "| | |", "|---|---|",
           "| Generated | {0} |".format(now),
           "| Commit | `{0}` on `{1}` |".format(sha or "unknown", branch or "unknown"),
           "| Lanes | {0} passed, {1} failed, {2} skipped |".format(
               len(passed), len(failed), len(skipped)),
           "| Tests counted | {0} |".format(total if total else "—"),
           "", verdict, "",
           "## Lanes", "",
           "| Lane | Result | Tests | Duration |", "|---|---|---:|---:|"]

    for r in rows:
        out.append("| {0} | {1} {2} | {3} | {4} |".format(
            r["label"], BADGE.get(r["status"], "•"), r["status"], r["count"], r["duration"]))

    if failed:
        out += ["", "## Failures", "",
                "Full output for each is under `test-results/<lane>.log`.", ""]
        for r in failed:
            out.append("- **{0}** — see `test-results/{1}.log`".format(r["label"], r["name"]))

    out += ["", "## Running these yourself", "",
            "```bash", "scripts/run_all_tests.sh              # every lane",
            "scripts/run_all_tests.sh python web   # a subset", "```", "",
            "Two environment traps the script handles for you, because neither error names its "
            "real cause:", "",
            "- **`cargo test` in `rulemind-core-rs` needs `--no-default-features`.** The default "
            "`python` feature pulls pyo3 `extension-module`, which deliberately does not link "
            "libpython, so a plain `cargo test` dies at link time on a missing `_Py_TrueStruct`.",
            "- **The Postgres lane needs `RULEMIND_TEST_PG_SCHEMA_PER_PATH=1` and a "
            "`postgresql://` URL.** Without the flag, 66 modules construct `Storage(path=…)` and "
            "silently re-run SQLite. With `postgresql+psycopg://` every module fails to import "
            "(`No module named 'psycopg'`) because requirements pins psycopg**2** — ~153 loader "
            "errors that look like a broken virtualenv.", ""]
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--summary", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    rows = read_summary(Path(args.summary))
    body = render(rows)
    Path(args.out).write_text(body)

    # Same numbers on the GitHub run page, at zero extra Actions cost.
    step_summary = os.getenv("GITHUB_STEP_SUMMARY")
    if step_summary:
        with open(step_summary, "a") as fh:
            fh.write(body)
    return 1 if any(r["status"] == "FAIL" for r in rows) else 0


if __name__ == "__main__":
    raise SystemExit(main())
