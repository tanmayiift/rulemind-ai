#!/usr/bin/env python3
"""Generate docs/connectors/TEMPLATES.md from app/connector_templates.py.

Generated, not written: the contract a template documents IS its configuration, so the page is
derived from it and `tests/test_connector_templates.py` fails when the committed page differs from
what this script would write. A hand-written contract page is the kind of document this repo has
repeatedly found saying something the code stopped doing.

    python scripts/gen_connector_template_docs.py          # write
    python scripts/gen_connector_template_docs.py --check  # exit 1 if stale
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "apps" / "python-executor"))

from app.connector_templates import TEMPLATES  # noqa: E402

OUT = ROOT / "docs" / "connectors" / "TEMPLATES.md"


def _render() -> str:
    lines = [
        "# Connector templates",
        "",
        "<!-- GENERATED by scripts/gen_connector_template_docs.py from "
        "apps/python-executor/app/connector_templates.py. Do not edit by hand. -->",
        "",
        "Prebuilt decision-time connectors for named providers. Install one with",
        "`POST /api/v1/connector-templates/{id}/install`; list them with",
        "`GET /api/v1/connector-templates`. Each installs a connector with `fetch_at_decision` on and",
        "`on_fetch_failure: review_gate`, plus starter variables in `dev`.",
        "",
        "**None of these has been run against the provider's live sandbox** — that needs credentials",
        "the provider issues to a customer. Each was built from the provider's published contract, and",
        "is tested end to end against a local server serving the provider's own documented example",
        "bodies. Every template lists what was and was not verified.",
        "",
        "A source a policy never reaches is not fetched, even with every variable computed: installing",
        "a bureau template does not turn unrelated decisions into bureau pulls.",
        "",
    ]
    for template in TEMPLATES.values():
        config = template["connector"]["config"]
        request = config.get("request_mapping", {})
        lines += [
            "## {0} — {1}".format(template["provider"], template["product"]),
            "",
            "`{0}` · category `{1}` · region {2} · default connector id `{3}`".format(
                template["id"], template["category"], template["region"], template["default_connector_id"]),
            "",
            template["description"],
            "",
            "Sources: " + " · ".join("[{0}]({1})".format(k, v) for k, v in template["sources"].items()),
            "",
            "### Verified ({0})".format(template["verification"]["checked_on"]),
            "",
        ]
        lines += ["- " + item for item in template["verification"]["verified"]]
        lines += ["", "### Not verified", ""]
        lines += ["- " + item for item in template["verification"]["not_verified"]]
        if template["verification"].get("discrepancies"):
            lines += ["", "### Contract discrepancies the template handles", ""]
            lines += ["- " + item for item in template["verification"]["discrepancies"]]
        lines += ["", "### Environments", "", "| environment | base URL |", "|---|---|"]
        lines += ["| {0} | `{1}` |".format(k, v) for k, v in template["environments"].items()]
        lines += ["", "Any other environment needs `base_url` at install.", ""]
        lines += ["### Install settings and secrets", "", "| key | kind | required | notes |", "|---|---|---|---|"]
        for spec in template["settings"]:
            note = spec["description"] + (" Default `{0}`.".format(spec["default"]) if spec.get("default") else "")
            lines.append("| `{0}` | setting | {1} | {2} |".format(spec["key"], "yes" if spec.get("required") else "no", note))
        for spec in template["secrets"]:
            lines.append("| `{0}` | secret | yes | {1} |".format(spec["key"], spec["description"]))
        lines += ["", "### Decision inputs", "", "| path | notes |", "|---|---|"]
        for spec in template["inputs"]:
            note = spec.get("description") or spec["label"] + "."
            if spec.get("pattern"):
                note += " Must match `{0}`.".format(spec["pattern"])
            lines.append("| `{0}` | {1} |".format(spec["path"], note))
        lines += ["", "A missing input fails as `missing_input` and a malformed one as `invalid_input`, "
                      "before any token request or provider call. The reason names the field, never the value.",
                  "", "### Request", "",
                  "`{0} {1}{2}`".format(request.get("method", "GET"), "<base_url>", request.get("path", "")), ""]
        if request.get("body") is not None:
            lines += ["```json", json.dumps(request["body"], indent=2, ensure_ascii=False), "```", ""]
        lines += ["### Response → source fields", "", "| field | path |", "|---|---|"]
        lines += ["| `{0}` | `{1}` |".format(k, v) for k, v in config.get("response_mapping", {}).items()]
        lines += ["", "### Error taxonomy", "", "| when | code |", "|---|---|"]
        for check in config.get("response_checks", []):
            allowed = ", ".join("`{0}`".format(v) for v in check.get("in", []))
            target = "`{0}`{1}".format(check["path"], "[]." + check["each"] if check.get("each") else "")
            if check.get("min_items"):
                lines.append("| 200, {0} has fewer than {1} item(s) | `{2}` |".format(target, check["min_items"], check["code"]))
            if allowed:
                for value, code in check.get("codes", {}).items():
                    lines.append("| 200, {0} is `{1}` | `{2}` |".format(target, value, code))
                lines.append("| 200, {0} is anything else outside {1} | `{2}` |".format(target, allowed, check["code"]))
        for status, code in config.get("error_codes", {}).items():
            lines.append("| HTTP {0} | `{1}` |".format(status, code))
        lines += ["| any other non-2xx, transport failure, timeout | the engine's generic codes |", ""]
        detail = config.get("error_detail_path")
        if detail:
            paths = [detail] if isinstance(detail, str) else detail
            lines += ["The provider's own error text ({0}) is carried in the failure reason, redacted.".format(
                ", ".join("`{0}`".format(p) for p in paths)), ""]
        lines += ["Only 408, 429 and 5xx are retried; a 4xx is the provider's answer about this request "
                  "and does not count against the circuit breaker.", ""]
        lines += ["### Starter variables (installed in `dev`)", "", "| id | meaning |", "|---|---|"]
        lines += ["| `<connector_id>_{0}` | {1} |".format(v["id"], v["description"]) for v in template["variables"]]
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    rendered = _render()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != rendered:
            print("docs/connectors/TEMPLATES.md is stale; run scripts/gen_connector_template_docs.py")
            return 1
        print("connector template docs current")
        return 0
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(rendered, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
